const API_PREFIX = "/api/v1";

let cachedPort: number | null = null;
let portPromise: Promise<number> | null = null;
let cachedToken: string | null = null;
let tokenPromise: Promise<string> | null = null;

/** True when running inside the Tauri webview (as opposed to a plain browser). */
function hasTauri(): boolean {
  return typeof window !== "undefined" && "__TAURI__" in window;
}

function tauriInvoke<T>(cmd: string): Promise<T> {
  const tauriGlobal = (window as unknown as {
    __TAURI__: { core: { invoke: (cmd: string) => Promise<T> } };
  }).__TAURI__;
  return tauriGlobal.core.invoke(cmd);
}

async function resolvePort(): Promise<number> {
  if (cachedPort !== null) return cachedPort;
  if (portPromise) return portPromise;

  portPromise = (async () => {
    if (hasTauri()) {
      try {
        const port = await tauriInvoke<number>("get_sidecar_port");
        if (typeof port === "number" && Number.isFinite(port) && port > 0) {
          cachedPort = port;
          return port;
        }
        throw new Error(`get_sidecar_port returned an invalid value: ${String(port)}`);
      } catch (err) {
        throw new Error(
          `Failed to resolve sidecar port via Tauri IPC: ${
            err instanceof Error ? err.message : String(err)
          }`,
        );
      }
    }

    const fallback = import.meta.env.VITE_SIDECAR_PORT;
    if (fallback) {
      const parsed = Number(fallback);
      if (Number.isFinite(parsed) && parsed > 0) {
        cachedPort = parsed;
        return parsed;
      }
    }

    throw new Error(
      "No sidecar port available: not running inside Tauri and VITE_SIDECAR_PORT is unset. " +
        "Set VITE_SIDECAR_PORT in a .env.local file to point at a manually started sidecar.",
    );
  })();

  try {
    return await portPromise;
  } finally {
    portPromise = null;
  }
}

async function resolveToken(): Promise<string> {
  if (cachedToken !== null) return cachedToken;
  if (tokenPromise) return tokenPromise;

  tokenPromise = (async () => {
    if (hasTauri()) {
      try {
        const token = await tauriInvoke<string>("get_sidecar_token");
        if (typeof token === "string" && token.length > 0) {
          cachedToken = token;
          return token;
        }
        throw new Error("get_sidecar_token returned an empty value");
      } catch (err) {
        throw new Error(
          `Failed to resolve sidecar auth token via Tauri IPC: ${
            err instanceof Error ? err.message : String(err)
          }`,
        );
      }
    }

    // Browser-fallback dev mode: VITE_SIDECAR_PORT users are expected to
    // set the same MASKFORGE_TOKEN the manually started sidecar printed
    // (it reads the env var back if present — see api/server.py).
    const fallback = import.meta.env.VITE_SIDECAR_TOKEN;
    if (fallback) {
      cachedToken = fallback;
      return fallback;
    }

    throw new Error(
      "No sidecar auth token available: not running inside Tauri and VITE_SIDECAR_TOKEN is unset.",
    );
  })();

  try {
    return await tokenPromise;
  } finally {
    tokenPromise = null;
  }
}

export class SidecarUnavailableError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "SidecarUnavailableError";
  }
}

export class ApiError extends Error {
  status: number;
  constructor(status: number, message: string) {
    super(message);
    this.name = "ApiError";
    this.status = status;
  }
}

async function request<T>(
  path: string,
  init?: RequestInit,
): Promise<T> {
  let port: number;
  let token: string;
  try {
    [port, token] = await Promise.all([resolvePort(), resolveToken()]);
  } catch (err) {
    throw new SidecarUnavailableError(
      err instanceof Error ? err.message : String(err),
    );
  }

  const url = `http://127.0.0.1:${port}${API_PREFIX}${path}`;
  let response: Response;
  try {
    response = await fetch(url, {
      ...init,
      headers: {
        "Content-Type": "application/json",
        "X-MaskForge-Token": token,
        ...init?.headers,
      },
    });
  } catch (err) {
    throw new SidecarUnavailableError(
      `Could not reach sidecar at ${url}: ${err instanceof Error ? err.message : String(err)}`,
    );
  }

  if (!response.ok) {
    let detail = response.statusText;
    try {
      const body = await response.json();
      if (body && typeof body === "object" && "detail" in body) {
        detail = String((body as { detail: unknown }).detail);
      }
    } catch {
      // body wasn't JSON, keep statusText
    }
    throw new ApiError(response.status, detail);
  }

  if (response.status === 204) {
    return undefined as T;
  }
  return (await response.json()) as T;
}

function get<T>(path: string): Promise<T> {
  return request<T>(path, { method: "GET" });
}

function post<T>(path: string, body?: unknown): Promise<T> {
  return request<T>(path, {
    method: "POST",
    body: body === undefined ? undefined : JSON.stringify(body),
  });
}

function put<T>(path: string, body: unknown): Promise<T> {
  return request<T>(path, { method: "PUT", body: JSON.stringify(body) });
}

function del<T>(path: string): Promise<T> {
  return request<T>(path, { method: "DELETE" });
}

/** Exposed for the status bar to display connection state without a full request. */
export async function getSidecarPort(): Promise<number> {
  return resolvePort();
}

/** Exposed for callers that need to authenticate a non-fetch channel (the
 * progress WebSocket, which can't set headers — see progressSocket.ts). */
export async function getSidecarToken(): Promise<string> {
  return resolveToken();
}

export async function resolveBaseUrl(): Promise<string> {
  const port = await resolvePort();
  return `http://127.0.0.1:${port}${API_PREFIX}`;
}

/**
 * Opens the native folder picker (Tauri's `pick_folder` command, backed by
 * tauri-plugin-dialog on the Rust side). Returns null if the user cancels,
 * or if running outside Tauri (plain browser dev mode has no native dialog
 * to fall back to).
 */
export async function pickFolder(): Promise<string | null> {
  if (!hasTauri()) return null;
  try {
    const tauriGlobal = (window as unknown as {
      __TAURI__: { core: { invoke: (cmd: string) => Promise<string | null> } };
    }).__TAURI__;
    return await tauriGlobal.core.invoke("pick_folder");
  } catch {
    return null;
  }
}

