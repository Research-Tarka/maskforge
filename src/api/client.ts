/**
 * HTTP client for the MaskForge sidecar API (see docs/IPC_CONTRACT.md).
 *
 * The sidecar port is not known at build time — it is assigned by the OS
 * and reported to the Tauri shell, which exposes it through the
 * `get_sidecar_port` IPC command. When running outside Tauri (plain
 * `npm run dev` in a browser, for local frontend iteration) we fall back to
 * the VITE_SIDECAR_PORT env var so the app still boots against a manually
 * started sidecar.
 *
 * The sidecar also requires a per-launch auth token (X-MaskForge-Token
 * header) on every request but /health — 127.0.0.1 is reachable by any
 * local process or browser tab, not just this app, and the port alone
 * isn't a secret. The token is generated by the sidecar itself and handed
 * to us the same way the port is, via `get_sidecar_token`; a malicious
 * page that merely guesses the port cannot forge it.
 */

